"""台账的取值表与两张表的分法。

为什么「类型」「负责环节」必须住这里、又为什么直到 2026-10-26 才补判据：
    AGENTS 与 [[任务台账]] 都写着「类型只能取这几类」，但没有任何脚本管它。
    取值写错不会让账本消失，只会让那一行**不再被读**——`plan` 按「负责环节＝采集」
    过滤，写成「采集入库」这一行就永远轮不到；类型写成「结构问题」，则「内容类缺档」
    与「结构错」在统计里混成一类。这与 T-20261026-01 的「后半条静默消失」同形：
    数据还在，只是没人再看它。

状态列不在此表：它是四态＋若干收尾写法（`✅ 已闭环`／`🚫 已放弃`／`⛔ 搁置`），
措辞本身还在演进，硬判会频繁误伤正确写法（见 MEMORY「判据宁窄不错认」）。
状态的卫生由 `check_ledger_hygiene` 按生命周期提示，不在这里判。

**两张表，不是一列（2026-10-28 第二版）**：
    上一版加了一列「解法」（机器／用户），想让人一眼看出「这条要不要我动手」。一列的问题
    不在表达，在**它只有人读、没人核**：填错了不报错，那一行从此被当成机器的事埋在
    采集清单里，几轮都没人发现。改成分两张表——「负责人＝机器」在上、「负责人＝用户」在下——
    同一件事就有了两个判据：表名要写出负责人（认不出就报错）；行只能待在一张表里，
    于是**换人＝搬行，搬行看得见**。列数同时回到 8：一列与一张表说同一件事，就是副本，
    副本迟早撒谎（同 AGENTS 第六节「副本归零」）。
"""
import re

# 八类，与 AGENTS 第十一节「台账类型」同集合；「内容」2026-10-26 补入
# （一手源取不到、存档不可用，既不是漏采也不是结构错）。
LEDGER_TYPES = ('漏采', '断档', '观点欠账', '结构', '归属', '重复', '机制', '内容')

# 五个负责环节。`plan` 只抽「采集」，其余由对应环节在体检/周观点里自查。
LEDGER_OWNERS = ('采集', '体检', '周观点', '分析', '用户')

# 「未闭环项」拆成两张表，取值即负责人；元组顺序＝文档里的顺序：
# 机器在办在上（每轮真会被派活），等你拍板在下（不进采集清单）。
# 注意它记的是「这条最后由谁消掉」，与「负责环节」不是一回事：负责环节说账在谁名下
# （内容欠账在采集、口径冲突在体检），负责人才回答「要不要我动手」。
LEDGER_TABLES = ('机器', '用户')

# 表名写法是契约：`### 2a 机器在办（负责人＝机器）`。
# 只认这个标记，不认「机器在办」「等你拍板」这类措辞——措辞会改，标记是判据。
OWNER_MARK = re.compile(r'负责人\s*[＝=]\s*(机器|用户)')

# 「未闭环项」的列序只在这里定义一次。此前下标散落在 plan、checks、ledger 三处，
# 加一列要同步改四处，漏一处就是静默读错列——而读错的形态恰好是「不报错、只是不再被读」，
# 与台账反复栽的那类事故同形。取值一律走 `col('状态')`，不再写裸下标。
LEDGER_COLS = ('编号', '首次发现', '问题', '类型', '负责环节',
               '状态', '最近更新', '关闭依据与下一步')
_COL = {name: i for i, name in enumerate(LEDGER_COLS)}


def col(name):
    """列名 → 下标。写错列名会 KeyError 而不是静默取到相邻列。"""
    return _COL[name]


def owner_of(heading):
    """小节标题 → 负责人（机器／用户）；认不出返回 None。

    返回 None 时不猜：由 `check_ledger_shape` 报「表名没写负责人」。
    猜的代价是那张表里的行被当成机器的活派出去，而它其实在等人。
    """
    m = OWNER_MARK.search(heading)
    return m.group(1) if m else None
