"""台账的取值表：「类型」与「负责环节」。

为什么必须住这里、又为什么直到 2026-10-26 才补判据：
    AGENTS 与 [[任务台账]] 都写着「类型只能取这几类」，但没有任何脚本管它。
    取值写错不会让账本消失，只会让那一行**不再被读**——`plan` 按「负责环节＝采集」
    过滤，写成「采集入库」这一行就永远轮不到；类型写成「结构问题」，则「内容类缺档」
    与「结构错」在统计里混成一类。这与 T-20261026-01 的「后半条静默消失」同形：
    数据还在，只是没人再看它。

状态列不在此表：它是四态＋若干收尾写法（`✅ 已闭环`／`🚫 已放弃`／`⛔ 搁置`），
措辞本身还在演进，硬判会频繁误伤正确写法（见 MEMORY「判据宁窄不错认」）。
状态的卫生由 `check_ledger_hygiene` 按生命周期提示，不在这里判。
"""

# 八类，与 AGENTS 第十一节「台账类型」同集合；「内容」2026-10-26 补入
# （一手源取不到、存档不可用，既不是漏采也不是结构错）。
LEDGER_TYPES = ('漏采', '断档', '观点欠账', '结构', '归属', '重复', '机制', '内容')

# 五个负责环节。`plan` 只抽「采集」，其余由对应环节在体检/周观点里自查。
LEDGER_OWNERS = ('采集', '体检', '周观点', '分析', '用户')

# 「解法」：这一条最终由谁消掉（2026-10-28 增）。
# 为什么不是「谁负责」：负责环节说的是**哪个环节的账**（内容欠账是采集的、口径冲突是体检的），
# 而读者真正要问的是另一件事——**这条要不要我动手**。两列同时在，才能一眼分出
# 「机器自己会做」与「等我拍板」。
# 只有两个值，是因为第三种没有位置：`run.py fix` 一条命令就能消掉的根本不该进台账，
# 能修就修了，登记它等于双重记账（见 AGENTS 第六节「副本归零」同一思路）。
LEDGER_SOLUTIONS = ('机器', '用户')

# 「未闭环项」的列序只在前端定义一次。此前 8 个下标散落在 plan、checks、ledger 三处，
# 加一列要同步改四处，漏一处就是静默读错列——而读错的形态恰好是「不报错、只是不再被读」，
# 与台账反复栽的那类事故同形。取值一律走 `col('状态')`，不再写裸下标。
LEDGER_COLS = ('编号', '首次发现', '问题', '类型', '负责环节',
               '解法', '状态', '最近更新', '关闭依据与下一步')
_COL = {name: i for i, name in enumerate(LEDGER_COLS)}


def col(name):
    """列名 → 下标。写错列名会 KeyError 而不是静默取到相邻列。"""
    return _COL[name]
