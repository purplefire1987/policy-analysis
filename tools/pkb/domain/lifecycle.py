#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""台账行的生命周期判据：多久算停滞、多久算待验过期、满多久该归档。

为什么放 domain 而不是写进 checks：这三个数会被**动作**（`run.py ledger`）与
**检查**（每期体检）同时引用。散在代码里，就会出现「脚本判 3 天、提示词写 5 天」
那种漂移——本库历史上规则副本漂移出过 4 次事故，起因都是同一个口径写了两份。

三个档位对应台账的四态（🆕 → 🟡 → ⏳ → ✅）：
    STALE_DAYS    🟡 在办超过这么久没动 → 退回 🆕（AGENTS 早给了这个权力，此前没人执行）
    VERIFY_DAYS   ⏳ 待验超过这么久没结论 → 提示：要么验，要么说清为什么验不了
    ARCHIVE_DAYS  ✅ 关闭满这么久 → 整行搬进「六、关闭记录」，不删行、只换位置
"""
import re

ARCHIVE_DAYS = 90      # ✅ 关闭满这么久 → 归档
STALE_DAYS = 3         # 🟡 在办超过这么久没动 → 退回 🆕
VERIFY_DAYS = 7        # ⏳ 待验超过这么久 → 提示

# 「观察窗口 2026-12」写在备注里，是这类任务的到期日（如等明年立法计划公布）。
# 中间可能夹 ** 或全角冒号，所以不写死紧邻。
OBSERVE = re.compile(r'观察窗口[^\d\n]{0,8}(\d{4})-(\d{2})')


# ── 已终止政策的归档口径（2026-10-28 定）──────────────────────────────
# 用户给定范围：**归档只处理已终止的政策**，不按时间归档。
# 理由（不是「少做点」）：按时间归档等于按重要性归档，而「三年前的判断」与
# 「三个月前的判断」在本库里价值相同；反过来，「已废止」是一个**事实判断**，
# 有明确依据（明文废止／被取代／失效），可以逐条核。
#
# 标记形态只有一个（AGENTS 第六节）：小节里一行
#     > **状态**：已废止（被 YYYY-MM-DD《新政策名》取代）
# 口径只在这里定义一次：检查（判据）与归档（列清单）都读它——
# 两处各写一份正则，就会出现「检查说已终止、归档不认」的分裂。
RETIRED_RE = re.compile(r'^\s*>\s*\*\*状态\*\*[：:]\s*(已废止|已失效|已终止|废止)(.*)$', re.M)


def retired(chunk):
    """小节正文 → (状态词, 余下说明) 或 None。

    余下说明必须写清「被谁取代」——只写「已废止」等于让读者自己去找替代者，
    而找替代者正是这张卡存在的原因。
    """
    m = RETIRED_RE.search(chunk or '')
    if not m:
        return None
    return m.group(1), m.group(2).strip()
