def views_state(chunk):
    """一个小节的「观点两节」状态：'a' 完整／'b' 待补全／'c' 无观点节。

    **只看「各方观点」到「影响判断」之间，不能整节 grep「（待补全）」**：
    文号栏也会写「（待补全）」（没查到的文号），那是另一件事。2026-10-28 踩过——
    补文号时给 16 个小节填了「（待补全）」，整节 grep 就把它们一并算成「观点待补全」，
    覆盖率从 83.4% 掉到 74.5%，看起来像补录倒退了 14 条。
    同一天还有另一处同形的坑：`check_structure` 的「关键词」判据曾把标题里已有的词
    抄进数组也不报。**判据认位置，不认「全节出现过这个字符串」。**
    """
    if '**各方观点**' not in chunk or '**观点辨析**' not in chunk:
        return 'c'
    seg = chunk.split('**各方观点**', 1)[1].split('**影响判断**')[0]
    return 'b' if '（待补全）' in seg else 'a'

